import Foundation

enum EmojiCategory: CaseIterable {
    case recentlyUsed
    case smileysAndPeople
    case animalsAndNature
    case foodAndDrink
    case activity
    case travelAndPlaces
    case objects
    case symbols
    case flags
    
    var displayIcon: String {
        switch self {
        case .recentlyUsed: return "🕐"
        case .smileysAndPeople: return "😊"
        case .animalsAndNature: return "🐻"
        case .foodAndDrink: return "🍔"
        case .activity: return "⚽"
        case .travelAndPlaces: return "✈️"
        case .objects: return "💡"
        case .symbols: return "♥️"
        case .flags: return "🏁"
        }
    }
    
    var displayName: String {
        switch self {
        case .recentlyUsed: return "Recently Used"
        case .smileysAndPeople: return "Smileys & People"
        case .animalsAndNature: return "Animals & Nature"
        case .foodAndDrink: return "Food & Drink"
        case .activity: return "Activity"
        case .travelAndPlaces: return "Travel & Places"
        case .objects: return "Objects"
        case .symbols: return "Symbols"
        case .flags: return "Flags"
        }
    }
    
    var emoji: [String] {
        switch self {
        case .recentlyUsed:
            return EmojiRecentsManager.shared.recentEmoji
        case .smileysAndPeople:
            return Self.smileysAndPeopleEmoji
        case .animalsAndNature:
            return Self.animalsAndNatureEmoji
        case .foodAndDrink:
            return Self.foodAndDrinkEmoji
        case .activity:
            return Self.activityEmoji
        case .travelAndPlaces:
            return Self.travelAndPlacesEmoji
        case .objects:
            return Self.objectsEmoji
        case .symbols:
            return Self.symbolsEmoji
        case .flags:
            return Self.flagsEmoji
        }
    }
    
    static var allCategories: [EmojiCategory] { allCases }
    
