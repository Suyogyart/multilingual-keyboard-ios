class EmojiRecentsManager {
    static let shared = EmojiRecentsManager()
    private let maxRecents = 30
    
    var recentEmoji: [String] {
        get {
            let raw = KeyboardSettings.shared.recentEmojiRaw
            guard !raw.isEmpty else { return [] }
            return raw.components(separatedBy: ",")
        }
        set {
            KeyboardSettings.shared.recentEmojiRaw = newValue.prefix(maxRecents).joined(separator: ",")
        }
    }
    
    func recordUsage(_ emoji: String) {
        var recents = recentEmoji
        recents.removeAll { $0 == emoji }
        recents.insert(emoji, at: 0)
        recentEmoji = Array(recents.prefix(maxRecents))
    }
}
