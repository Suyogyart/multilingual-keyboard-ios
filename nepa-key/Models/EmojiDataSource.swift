    func suggestions(for prefix: String, limit: Int = 3) -> [String] {
        let lowered = prefix.lowercased()
        
        if let exact = keywordMap[lowered] {
            return Array(exact.prefix(limit))
        }
        
        var results: [String] = []
        for (keyword, emojis) in keywordMap {
            if keyword.hasPrefix(lowered) {
                results.append(contentsOf: emojis)
            }
        }
        
        let unique = results.reduce(into: [String]()) { acc, e in
            if !acc.contains(e) { acc.append(e) }
        }
        return Array(unique.prefix(limit))
    }
